"""Hypencoder graph-based retrieval module for ML Research RAG.

This module implements the retrieval strategy described in:
"Hypencoder: Hypernetworks for Information Retrieval" (Killingback et al., 2025).
https://arxiv.org/pdf/2502.05364

Instead of static inner products, Hypencoder dynamically generates a small query-specific
scoring network (q-net) via a hypernetwork query encoder. Candidate document embeddings
(generated by Hypencoder's passage encoder) are passed through the q-net to compute
non-linear relevance scores. A neighbor graph in Euclidean (L2) embedding space is traversed
to quickly discover the highest-scoring document chunks.
"""

import heapq
import os
import random
from typing import Any, Dict, List, Optional, Set, Tuple

import numpy as np
import torch
from transformers import AutoTokenizer

from hypencoder_cb.modeling.hypencoder import HypencoderDualEncoder

DEFAULT_MODEL_NAME = "jfkback/hypencoder.6_layer"
DEFAULT_COLLECTION = "document_chunks_hypencoder"


def get_default_device() -> str:
    """Select appropriate device for inference."""
    env_dev = os.getenv("HYPENCODER_DEVICE")
    if env_dev:
        return env_dev
    if torch.cuda.is_available():
        return "cuda"
    return "cpu"


_MODEL_CACHE: Dict[str, Tuple[HypencoderDualEncoder, Any]] = {}


def load_hypencoder(
    model_name: str = DEFAULT_MODEL_NAME,
    device: Optional[str] = None,
) -> Tuple[HypencoderDualEncoder, Any]:
    """Load and cache the Hypencoder dual encoder and tokenizer.

    If Streamlit is running, this function leverages st.cache_resource if available,
    otherwise uses an internal in-process cache.
    """
    if device is None:
        device = get_default_device()

    cache_key = f"{model_name}_{device}"
    if cache_key in _MODEL_CACHE:
        return _MODEL_CACHE[cache_key]

    # Try Streamlit cache if inside Streamlit app context
    try:
        import streamlit as st

        @st.cache_resource(show_spinner=False)
        def _cached_loader(name: str):
            m = HypencoderDualEncoder.from_pretrained(name)
            t = AutoTokenizer.from_pretrained(name)
            m.eval()
            return m, t

        model, tokenizer = _cached_loader(model_name)
    except Exception:
        model = HypencoderDualEncoder.from_pretrained(model_name)
        tokenizer = AutoTokenizer.from_pretrained(model_name)
        model.eval()

    _MODEL_CACHE[cache_key] = (model, tokenizer)
    return model, tokenizer


def score_candidates_with_qnet(
    model: HypencoderDualEncoder,
    tokenizer: Any,
    query: str,
    candidate_embeddings: torch.Tensor,
    device: Optional[str] = None,
    query_max_length: int = 64,
) -> torch.Tensor:
    """Score candidate embeddings using query-generated q-net.

    Args:
        model: HypencoderDualEncoder instance.
        tokenizer: Hugging Face tokenizer for Hypencoder.
        query: User search query string.
        candidate_embeddings: Tensor of shape (num_candidates, 768).
        device: Device to run computation on.
        query_max_length: Maximum token length for the query.

    Returns:
        1D Tensor of shape (num_candidates,) containing relevance scores.
    """
    if device is None:
        device = next(model.parameters()).device

    inputs = tokenizer(
        [query],
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=query_max_length,
    ).to(device)

    with torch.no_grad():
        q_nets = model.query_encoder(
            input_ids=inputs["input_ids"],
            attention_mask=inputs["attention_mask"],
        ).representation

        cand_tensor = candidate_embeddings.unsqueeze(0).to(device, dtype=torch.float32)
        scores = q_nets(cand_tensor).view(-1)

    return scores


class HypencoderGraphRetriever:
    """Graph-based approximate nearest neighbor retriever with Hypencoder q-nets.

    Stores document passage embeddings (768-dim) and their L2 neighbor graph in Qdrant,
    maintains an optional in-memory working cache for rapid graph traversal, and uses
    dynamically generated q-nets to score nodes during graph navigation.
    """

    def __init__(
        self,
        client: Any,
        collection_name: str = DEFAULT_COLLECTION,
        model: Optional[HypencoderDualEncoder] = None,
        tokenizer: Optional[Any] = None,
        device: Optional[str] = None,
        preload_limit: Optional[int] = 5000,
    ) -> None:
        self.client = client
        self.collection_name = collection_name
        self.device = device or get_default_device()

        if model is None or tokenizer is None:
            self.model, self.tokenizer = load_hypencoder(device=self.device)
        else:
            self.model = model
            self.tokenizer = tokenizer

        # In-memory working cache for fast graph traversal
        self._vector_cache: Dict[Any, torch.Tensor] = {}
        self._payload_cache: Dict[Any, Dict[str, Any]] = {}
        self._all_known_ids: List[Any] = []

        if preload_limit and preload_limit > 0:
            self._preload_cache(max_points=preload_limit)

    def _preload_cache(self, max_points: int = 5000) -> None:
        """Preload a subset or all points into local memory for rapid search."""
        try:
            if not self.client.collection_exists(self.collection_name):
                return

            offset = None
            loaded = 0
            while loaded < max_points:
                batch_limit = min(500, max_points - loaded)
                points, next_offset = self.client.scroll(
                    collection_name=self.collection_name,
                    limit=batch_limit,
                    offset=offset,
                    with_payload=True,
                    with_vectors=True,
                )
                if not points:
                    break

                for p in points:
                    if p.vector is not None:
                        vec_tensor = torch.tensor(p.vector, dtype=torch.float32)
                        self._vector_cache[p.id] = vec_tensor
                        self._payload_cache[p.id] = p.payload or {}
                        self._all_known_ids.append(p.id)
                        loaded += 1

                if next_offset is None:
                    break
                offset = next_offset
        except Exception as e:
            print(f"[WARN] Failed to preload Hypencoder cache: {e}", flush=True)

    def _fetch_points(self, point_ids: List[Any]) -> None:
        """Fetch missing points (vectors + payloads) from Qdrant on demand."""
        missing = [pid for pid in point_ids if pid not in self._vector_cache]
        if not missing:
            return

        try:
            records = self.client.retrieve(
                collection_name=self.collection_name,
                ids=missing,
                with_payload=True,
                with_vectors=True,
            )
            for r in records:
                if r.vector is not None:
                    self._vector_cache[r.id] = torch.tensor(r.vector, dtype=torch.float32)
                    self._payload_cache[r.id] = r.payload or {}
                    if r.id not in self._all_known_ids:
                        self._all_known_ids.append(r.id)
        except Exception as e:
            print(f"[WARN] Error fetching points from Qdrant: {e}", flush=True)

    def retrieve(
        self,
        query: str,
        k: int = 50,
        num_entry_points: int = 50,
        ncandidates: int = 25,
        max_iter: int = 16,
    ) -> List[Dict[str, Any]]:
        """Perform graph-based retrieval using Hypencoder q-net scoring.

        Args:
            query: The search query text.
            k: Number of top documents to return.
            num_entry_points: Number of initial starting nodes.
            ncandidates: Number of top candidates to expand neighbors from at each step.
            max_iter: Maximum graph traversal expansion iterations.

        Returns:
            List of result dicts matching the call_vector_db interface:
            [{"id": ..., "source": ..., "text": ..., "score": ..., "metadata": ...}]
        """
        # 1. Encode query to produce q-net
        inputs = self.tokenizer(
            [query],
            return_tensors="pt",
            padding=True,
            truncation=True,
            max_length=64,
        ).to(self.device)

        with torch.no_grad():
            q_nets = self.model.query_encoder(
                input_ids=inputs["input_ids"],
                attention_mask=inputs["attention_mask"],
            ).representation

        # 2. Select initial entry points
        if not self._all_known_ids:
            self._preload_cache(max_points=max(num_entry_points * 2, 200))

        if not self._all_known_ids:
            # Collection might be empty
            return []

        sample_k = min(num_entry_points, len(self._all_known_ids))
        candidates = random.sample(self._all_known_ids, sample_k)
        explored: Set[Any] = set(candidates)

        # Min-heap to maintain top k items: (score, tie_breaker, point_id, payload)
        heap: List[Tuple[float, int, Any, Dict[str, Any]]] = []
        tie_breaker = 0

        # 3. Iterative graph traversal
        for iter_idx in range(max_iter):
            if not candidates:
                break

            self._fetch_points(candidates)
            valid_candidates = [cid for cid in candidates if cid in self._vector_cache]
            if not valid_candidates:
                break

            cand_vectors = torch.stack(
                [self._vector_cache[cid] for cid in valid_candidates]
            ).to(self.device, dtype=torch.float32)

            with torch.no_grad():
                cand_tensor = cand_vectors.unsqueeze(0)  # Shape (1, N, 768)
                sim_scores = q_nets(cand_tensor).view(-1).cpu().tolist()

            scored = list(zip(valid_candidates, sim_scores))
            scored.sort(key=lambda x: x[1], reverse=True)

            added_to_heap = False
            for cid, score in scored:
                payload = self._payload_cache.get(cid, {})
                if len(heap) < k:
                    tie_breaker += 1
                    heapq.heappush(heap, (score, tie_breaker, cid, payload))
                    added_to_heap = True
                else:
                    if score > heap[0][0]:
                        tie_breaker += 1
                        heapq.heapreplace(heap, (score, tie_breaker, cid, payload))
                        added_to_heap = True

            # Early stopping condition: if no candidates entered heap after iter 0
            if not added_to_heap and iter_idx > 0:
                break

            # Expand neighbors for top ncandidates
            next_candidates: List[Any] = []
            for cid, _ in scored[:ncandidates]:
                payload = self._payload_cache.get(cid, {})
                neighbors = payload.get("neighbors") or []
                for n_id in neighbors:
                    if n_id not in explored:
                        explored.add(n_id)
                        next_candidates.append(n_id)

            candidates = next_candidates

        # 4. Format and sort final results
        results = []
        while heap:
            score, _, cid, payload = heapq.heappop(heap)
            text = payload.get("text", "")
            source = payload.get("source") or payload.get("filename") or "unknown"
            meta = {
                k_val: v_val
                for k_val, v_val in payload.items()
                if k_val not in ("text", "source", "_stable_id", "neighbors")
            }
            pid_str = payload.get("_stable_id") or str(cid)
            results.append(
                {
                    "id": pid_str,
                    "source": source,
                    "text": text,
                    "score": float(score),
                    "metadata": meta,
                }
            )

        # Sort descending by score
        results.reverse()
        return results
